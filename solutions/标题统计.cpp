/*
 * 标题统计（洛谷 P5015，NOIP2018 普及组）
 * ────────────────────────────────────────────────────────────
 * 题意
 *   读入一行（可能只有一个词，也可能带空格），数出其中「非空格字符」的个数。
 *
 * 思路
 *   整行读进来用 getline，然后数不是空格的字符。
 *   我这版是「总数 - 空格数」的写法；下面注释里给了更直接的写法。
 *
 * 重点：getline 到底做了什么
 *   getline(cin, line) = 从当前位置读到 '\n' 为止，
 *   内容装进 line，并且把那个 '\n' 吃掉、丢掉。
 *
 *   所以两件事：
 *     - 这一行里的空格是原样保留的（这正是这题需要 getline 的原因，
 *       用 cin >> 读会在第一个空格处停下）；
 *     - line 里面永远不含 '\n'。
 *
 * 踩过的坑
 *   1) 我写了 if (line[i] == ' ' || line[i] == '\n') —— '\n' 那一支是死代码，
 *      getline 已经把换行吃掉了，line 里不可能有 '\n'。留着无害，但说明我没搞清它干了什么。
 *   2) getline 最大的陷阱在「前面刚用过 cin >> 数字」的时候：
 *      cin >> n 读完数字，那个 '\n' 还留在输入流里，
 *      紧跟的 getline 立刻遇到它 → 读到一个空字符串就返回。
 *      修法是加一句 cin.ignore();
 *      这题我没撞上，纯粹因为 main 里第一句就是 getline、流里干干净净 —— 是顺序刚好，不是我会。
 *   3) (int)line.size() 这个 cast 要有：size() 返回的是无符号的 size_t，
 *      直接拿去和 int 混算容易出意料之外的结果。
 *
 * 更省事的写法（少一个可能出错的地方）
 *   int cnt = 0;
 *   for (char c : line) if (c != ' ') cnt++;
 *   cout << cnt << '\n';
 *
 * 复杂度
 *   O(长度)。
 * ────────────────────────────────────────────────────────────
 */
#include <bits/stdc++.h>
using namespace std;

int main()
{
    string line;
    getline(cin, line);                      // 读一整行，空格也读进来

    int cnt = 0;
    for (int i = 0; i < (int)line.size(); i++) {
        if (line[i] == ' ' || line[i] == '\n') {   // '\n' 这一支其实走不到
            cnt++;
        }
    }
    cout << (int)line.size() - cnt << '\n';  // 总数 - 空格数 = 非空格字符数
    return 0;
}