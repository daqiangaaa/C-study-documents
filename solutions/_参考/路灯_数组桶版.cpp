/*
 * 路灯 · 数组桶版（同一题 AC 之后的另一种写法）
 * ───────────────────────────────────────────────────────────────
 * 和 路灯.cpp 的差别只有三点，全部是从数据范围里读出来的：
 *
 *   ① map → 数组
 *      题目给了 t_i × a_i ≤ 2000000，也就是「灯号最大 2e6」，
 *      下标是有上界的 ⇒ 用不着 map，直接开一个 bool 数组当桶。
 *      （STL 不是「更好」，是「更通用」。范围已知且有上界时，数组永远赢。）
 *
 *   ② ++  →  ^= 1
 *      我们只关心「奇数次还是偶数次」，根本不关心按了几次，
 *      所以直接翻转比计数更浅一层、也更快。
 *
 *   ③ 把浮点彻底干掉
 *      题面「小数点后固定 6 位」是白送的条件：a 一定是有限小数 ⇒
 *      A = a × 1000000 是整数，于是
 *          floor(j*a) = j*A / 1000000
 *      用整数除法（正数时就是向下取整），误差为 0，
 *      不用再纠结该加 1e-9 还是 1e-6。
 *
 *      为什么 llround 能还原准确？a < 1000 ⇒ a*1e6 < 1e9，
 *      double 有 15~16 位有效数字，绝对误差 < 1e-7，四舍五入必回原整数。
 *      会不会溢出？j ≤ 2e6、A ≤ 1e9 ⇒ j*A ≤ 2e15，
 *      long long 上限 9.2e18，安全。
 *
 * 实测（最坏情况 T = 2e6、灯号两两不同）
 *   map 版   0.52 秒 / 93 MB
 *   数组版   0.068 秒 / 3.3 MB
 * ───────────────────────────────────────────────────────────────
 */
#include <bits/stdc++.h>
using namespace std;

const int MAXV = 2000005;          // 灯号上界 2e6，多开 5 格保险
static bool on[MAXV];              // on[i] = 1 表示第 i 盏灯最后是开着的

int main()
{
    int n;
    if (scanf("%d", &n) != 1) return 0;

    for (int i = 0; i < n; i++) {
        double a;
        int t;
        scanf("%lf %d", &a, &t);            // double 在 scanf 里必须 %lf

        long long A = llround(a * 1000000.0);        // 1.618034 → 1618034
        for (int j = 1; j <= t; j++) {
            long long idx = (long long)j * A / 1000000;   // 整数除法 = 向下取整
            on[idx] ^= 1;                                 // 翻转，不计数
        }
    }

    // 只有一盏是开着的，扫到第一个就是答案
    for (int i = 1; i < MAXV; i++) {
        if (on[i]) { printf("%d\n", i); return 0; }
    }
    return 0;
}
