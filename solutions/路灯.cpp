/*
 * 路灯
 * ───────────────────────────────────────────────────────────────
 * 题意
 *   一条无限长的路上有路灯 1, 2, 3, …，一开始全关。
 *   有 n 次操作，每次给一个实数 a（小数点后固定 6 位）和一个正整数 t，
 *   把编号为  floor(1*a), floor(2*a), …, floor(t*a)  的灯各按一次
 *   （按一次翻转一次：关→开、开→关）。
 *   n 次操作完之后，恰好有且只有一盏灯是开着的（数据保证），求它的编号。
 *
 * 范围
 *   T = Σt_i ≤ 2000000；n ≤ 5000；1 ≤ a_i < 1000；1 ≤ t_i ≤ T；
 *   所有 i 都满足 t_i × a_i ≤ 2000000  ⇒  灯号最大就是 2 000 000
 *
 * 我这版的思路
 *   map 当桶用：键 = 灯号，值 = 这个灯被按了几次。
 *   最后从小到大扫一遍，第一个「按了奇数次」的就是答案。
 *
 * 代价（事后才算的）
 *   时间 O(T log T)、内存 O(T)。
 *   最坏情况（T = 2e6、灯号两两不同）本机实测 0.52 秒 / 93 MB ——
 *   内存贴着 128 MB 的线过，是个「能过但不该这么写」的解。
 *   更好的写法见 _参考/路灯_数组桶版.cpp：O(T)、3.3 MB。
 * ───────────────────────────────────────────────────────────────
 */
#include <bits/stdc++.h>
using namespace std;

int main()
{
    map<int, int> mp;              // 灯号 -> 被按了几次

    int n;
    cin >> n;

    int t;
    double a;                      // a 是实数，必须是 double
    for (int i = 0; i < n; i++) {
        cin >> a >> t;

        // 第 j 次按的是 floor(j * a)，j 从 1 数到 t
        for (int j = 1; j <= t; j++) {
            mp[(int)j * a]++;
            // ⚠️ 这里的强制转换位置其实是错的：写的是 (int)j * a，
            //    先把 j 转成 int（等于没转），再 int * double 得 double，
            //    最后塞进 map<int,int> 时 double 向零截断成 int。
            //    正数时「截断」和「向下取整」恰好一样，所以碰巧对了；
            //    但 a 一旦可能为负、或者以后照抄到别的题里，它就错。
            //    想表达 floor(j*a)，应该写 (int)(j * a)。
        }
    }

    // 从小到大扫：按了奇数次 = 最后是开着的
    for (auto &kv : mp) {
        if (kv.second % 2 == 1) {
            cout << kv.first << '\n';
            break;                 // 题目保证只有一盏，找到就停
        }
    }
    return 0;
}
