/*
 * 成绩排名 —— 「桶计数 + 前缀和」逐步演示
 *
 * 题目：n 个学生各有成绩（1 ~ 100），m 次询问，每次给一个编号，
 *       求这个学生的成绩在班里排倒数第几（并列时名次跳号）。
 *       倒数第几 = 1 + 比我分低的人数
 *
 * 两种写法：
 *   ① 双重循环：每问一次就把全班扫一遍      O(n * m)
 *   ② 桶计数 + 前缀和：先把「每个分数」的答案算成一张表，问的时候 O(1) 查
 *      这个文件演示的就是 ②，并把中间的两张表打出来。
 *
 * 运行：以 Code::Blocks 直接运行本文件，按题目格式输入，例如
 *           4 1
 *           1 2 2 3
 *           4
 *       程序会先打印 cnt[] 和 less[]，再逐个回答询问。
 *
 * 提示：想让中间过程更丰富，可以自己换成
 *           4 4
 *           1 2 2 3
 *           1 2 3 4
 */
#include <stdio.h>

#define MAXS 100                 /* 成绩最大 100（题目给的值域） */

static int cnt[MAXS + 5];        /* cnt[s]  = 考 s 分的有几个人 */
static int less[MAXS + 5];       /* less[s] = 比 s 分低的有几个人 */

int main(void)
{
    int n, m, a[105] = {0}, q[105] = {0};
    int i, k, s;
    int lo = MAXS, hi = 1;       /* 实际出现过的最低分 / 最高分，只为把表打窄一点 */
    int slow[MAXS + 5] = {0};    /* 用「笨办法」算出来的 less[]，用来对照 */
    int same = 1, tmp;

    if (scanf("%d%d", &n, &m) != 2) return 0;

    /* ---------- 第一步：装桶 ---------- */
    for (i = 0; i < n; i++)
    {
        scanf("%d", &a[i]);
        cnt[a[i]]++;             /* 考 a[i] 分的人多了一个 */
        if (a[i] < lo) lo = a[i];
        if (a[i] > hi) hi = a[i];
    }
    for (k = 0; k < m; k++) scanf("%d", &q[k]);

    printf("\n=========================================================\n");
    printf(" 1. 装桶  cnt[s] = 考 s 分的有几个人\n");
    printf("    （下标不是「编号」而是「分数」—— 分数相同的全进同一个桶）\n");
    printf("=========================================================\n");
    printf("    分数 :");
    for (s = lo; s <= hi; s++) printf("%5d", s);
    printf("\n    人数 :");
    for (s = lo; s <= hi; s++) printf("%5d", cnt[s]);
    printf("\n\n");

    /* ---------- 第二步：算 less[]，两种算法对照 ---------- */

    /* 笨办法：把比 s 小的桶一个一个加起来 —— 直白，但慢 */
    for (s = 1; s <= MAXS; s++)
    {
        tmp = 0;
        for (i = 1; i < s; i++) tmp += cnt[i];
        slow[s] = tmp;
    }

    /* 聪明办法（前缀和）：相邻两格只差一项 cnt[s-1] */
    /*   less[s]   = cnt[1] + ... + cnt[s-2] + cnt[s-1]
         less[s-1] = cnt[1] + ... + cnt[s-2]
         所以 less[s] = less[s-1] + cnt[s-1]                */
    less[1] = 0;                 /* 成绩至少 1 分，比 1 分低的必然是 0 个 */
    for (s = 2; s <= MAXS; s++) less[s] = less[s - 1] + cnt[s - 1];

    for (s = 1; s <= MAXS; s++) if (slow[s] != less[s]) same = 0;

    printf("=========================================================\n");
    printf(" 2. 算 less[s] = 比 s 分低的有几个人\n");
    printf("    笨办法 : 把 1 ~ s-1 号桶一个一个加起来\n");
    printf("    前缀和 : less[s] = less[s-1] + cnt[s-1]   （走一趟就完事）\n");
    printf("=========================================================\n");
    printf("    分数 :");
    for (s = lo; s <= hi; s++) printf("%5d", s);
    printf("\n    笨办法:");
    for (s = lo; s <= hi; s++) printf("%5d", slow[s]);
    printf("\n    前缀和:");
    for (s = lo; s <= hi; s++) printf("%5d", less[s]);
    printf("\n    两种算法结果%s\n\n", same ? "一模一样，说明化简没有改错" : "不一致（不该发生，出 bug 了）");

    /* ---------- 第三步：查表回答 ---------- */
    printf("=========================================================\n");
    printf(" 3. 逐个回答：倒数第几 = 1 + less[我的分数]\n");
    printf("=========================================================\n");
    for (k = 0; k < m; k++)
    {
        int who = q[k];
        int sc  = a[who - 1];    /* 编号从 1 开始，数组从 0 开始 */
        printf("    问第 %2d 号 -> 他考 %2d 分 -> 1 + less[%d] = 1 + %d = %d\n",
               who, sc, sc, less[sc], 1 + less[sc]);
    }
    printf("    （分数相同的人查的是同一个格子，所以并列时名次自动相同 —— \n");
    printf("      题面要求的「并列跳号」是白送的，不用写任何特判）\n\n");

    /* ---------- 第四步：最终答案（拿去和双重循环版对拍） ---------- */
    printf("=========================================================\n");
    printf(" 4. 最终答案\n");
    printf("=========================================================\n");
    for (k = 0; k < m; k++) printf("%d\n", 1 + less[a[q[k] - 1]]);

    return 0;
}
