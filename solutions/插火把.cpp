/*
 * 【Mc生存】插火把 —— 洛谷 P1789
 * ───────────────────────────────────────────────────────────────
 * 题意
 *   n×n 的方阵（坐标 1..n）。放 m 个火把、k 个萤石。
 *   火把照亮周围 5×5 里的 13 格，萤石照亮整个 5×5 共 25 格。
 *   没有光、也没放东西的格子会生成怪物，问这种格子有几个。
 *
 * 范围
 *   1 ≤ n ≤ 100，1 ≤ m ≤ 25，0 ≤ k ≤ 5，1 ≤ m+k ≤ 25
 *   数据里可能没有萤石，但一定有火把。
 *
 * 两个形状其实是同一个公式
 *   火把：|dx| + |dy| ≤ 2       ← 曼哈顿距离，正好是那个十字形
 *   萤石：|dx| ≤ 2 且 |dy| ≤ 2   ← 就是整个 5×5
 *   所以那张 5×5 的表根本不用抄，一个 abs 就够，也就没有「表抄错」的机会。
 *
 * 踩过的坑（这题我改了两轮才对，编译器一个字都没警告）
 *   ① 边界判断里的下标，必须和真正写入用的那个是同一个变量。
 *      第一版我手写了 j+a+2 >= n（本该是 j+a-2 >= n），
 *      代进样例 a=3、n=5 就是 j+5>=5 恒成立 ⇒ 25 格全被 continue，
 *      一个字都没写进去 ⇒ 输出 0。
 *   ② 坐标系只能有一个基准。输入是 1..n，我却用 x<0 || x>=n 去卡，
 *      结果整块光照区右下偏一格，还被右边和下边的墙裁掉。
 *      修法：读入后立刻 --a; --b; 之后一律按 0 基走。
 *   ③ 光照不能「赋值」（area = 表里的值）—— 暗格会把人家的光擦掉，
 *      必须「只置 1」。
 *   ④ 题目问的是「会生成怪物」的点 = 没光的格子，
 *      我一开始数成了有光的。
 * ───────────────────────────────────────────────────────────────
 */
#include <bits/stdc++.h>
using namespace std;

int area[105][105];          // area[x][y] = 1 表示这个格子有光

int main()
{
    int n, m, d;
    cin >> n >> m >> d;

    int a, b;

    // ---- 火把：照亮 |dx| + |dy| ≤ 2 ----
    for (int i = 0; i < m; i++) {
        cin >> a >> b;
        --a; --b;                 // 输入是 1 基，进来立刻转成 0 基

        for (int dx = -2; dx <= 2; dx++) {
            for (int dy = -2; dy <= 2; dy++) {
                int x = dx + a;
                int y = dy + b;
                // 边界就用真实的 x、y 判断，别另写一份表达式
                if (x < 0 || x >= n || y < 0 || y >= n) continue;
                if (abs(dx) + abs(dy) <= 2) area[x][y] = 1;
            }
        }
    }

    // ---- 萤石：照亮整个 5×5 ----
    for (int i = 0; i < d; i++) {
        cin >> a >> b;
        --a; --b;

        for (int dx = -2; dx <= 2; dx++) {
            for (int dy = -2; dy <= 2; dy++) {
                int x = dx + a;
                int y = dy + b;
                if (x < 0 || x >= n || y < 0 || y >= n) continue;
                area[x][y] = 1;   // 25 格全亮，不用再判
            }
        }
    }

    // ---- 数「没光的」格子 ----
    int cnt = 0;
    for (int i = 0; i < n; i++)
        for (int j = 0; j < n; j++)
            if (area[i][j] == 0) cnt++;

    cout << cnt << '\n';
    return 0;
}
